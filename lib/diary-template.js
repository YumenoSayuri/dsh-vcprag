/** 内置模板。 */
export const BUILT_IN_TEMPLATE = `## 日记写作规范

日记是你的长期记忆。每一篇都会被向量化入库，在未来某次对话的语义检索中苏醒——成为彼时思考的血肉。日记的品质，就是记忆的分辨率。

### 何时落笔

对话中结晶出了值得保存的新知识、新经历、新判断时再写。等事件脉络完整、认知真正成型再写——在回复的末尾，所有思考与工具调用完成之后，作为自然的沉淀落下。用户正在分享一段完整事件时，耐心等它讲完。

**严禁在对话中途或消息开头穿插日记。** 必须先完成所有交互，最后统一记录。落笔前先确认一件事：**这个会话已经写过日记了吗？写过就先想 update——除非这次的记录确实与当篇完全无关。**

### 一个会话通常一篇

**默认一个会话只落一篇日记**——因为一个会话通常都在处理同一件事，后续的补充、修正、追加结论自然属于同一篇。会话内第一次落笔用 create，之后就改用 update。

**确实完全无关时可以另开**：会话中途切到一个全新项目、和当篇主题毫无交集，硬塞进去反而把两件事搅成一锅——这时候另开一篇是对的，不必勉强合并。判断口诀：**这一篇还能接住吗？能，就 update；接不住，才另开。**

写偏了同样用 update 修，不要 create「修正版」。同一件事裂成多篇，召回时会命中碎片而不是完整链条，等于白写。

反例（下面这些是本该 update 却 create 了第二篇）：

- 会话里已有一篇「热层整理」，半小时后又 create 一篇「热层整理（补充）」→ 应当 update 当篇。
- 一路排障，最后觉得「这个坑值得单独记」→ 这个坑就是本会话的一部分，update 当篇，不要拆出去。
- 会话已有一篇，忽然想写「感悟」→ 感悟属于同一次交流，update 当篇。

### update 不是只追加，要顺手整理

最容易做错的地方：把 update 当成「在末尾再挂一节」。这样一篇会越挂越长，几个版本叠在一起，后来读的人和检索都得从流水账里捞结论。

**每次 update 前先通读当篇**，然后按四件事处理：

1. **删过时的**：被推翻的结论、后来证明是错的假设，直接替换或删掉，不要留着让读者猜哪个是最终版。
2. **改冲突的**：新旧说法矛盾时改成一处正确表述，不要两段并存。
3. **合重复的**：同一件事在几节里各说一遍，合并成一节。
4. **精简啰嗦的**：反复铺陈的铺垫、没有信息量的过程描述，压成一句。

**判断标准**：update 完之后，这一篇读下来应该是一条清晰的主线，而不是按时间排列的流水账；篇幅应该和「这件事有多少有效信息」相称，不随会话轮次线性增长。

比起「追加一节」，更高优先级的是「让这一篇更准、更短」。

### 会话内 update 的手法

想「改一句」「加一节」「删旧段」，都走 update，区别只在 target 怎么选：

- 改某段：target 取那段原文，replace 成新的说法。
- 删过时段：target 取那段原文，replace 传空串。
- 整理并新增：target 取那段原文，replace 写成「改写后的原文 + 新内容」，一步完成整理与追加。
- 末尾追加（确定旧段全都要留时）：target 取当篇最后一段（连同 Tag 行一起取最省事），replace 写成「原最后一段 + 新内容 + 更新后的 Tag 行」。
- 大改：先用 \`vcprag_read\` 读出全文，想清楚哪几段该留、该改、该删，再逐段 update 或整篇重构。
- 不确定原文长什么样：先用 \`vcprag_search\` 找到那篇，再 \`vcprag_read\` 读正文。不要凭印象编 target，逐字对不上会被拒绝。

### 一篇之内怎么组织

一篇日记可以有多节。同一话题在同一会话里涌现多个事件时，让它们在同一篇里各占一节，小标题写清各自的主题——并联在一篇之内，而不是拆成多篇。整理后某节如果已经空了、或者已经被别的节吸收，就把那节删掉。Tag 跟着整理后的结构走，而不是跟着追加顺序走。

### 信息密度

拒绝为了简短而简短。每条记录必须包含完整的起因、过程、结果，逻辑链条完整，严禁模糊处理。记录应包含的核心要素：

1. **核心主题**：一句话概括事件目标。
2. **完整背景**：事件触发的前因，包括背景条件、原始需求或突发状况。
3. **详细经过**：完整路径，包括处理方法、关键决策点、思考逻辑、解决冲突的过程、尝试过但失败的方案，以及为何选择当前方案。
4. **明确结果**：最终交付成果、结论或当前状态，以及后续影响。
5. **关键数据与实体**：项目名称、关键参数、时间节点、工具名称、特定技术点、关键路径或代码信息。
6. **深度复盘**：经验教训、逻辑沉淀、可优化空间。

用有血有肉的真实叙事维持信息密度，不要写成冷冰冰的汇报大纲。

### 时间

正文以 \`[HH:MM]\` 开头。这个时间从用户消息末尾的当前时间提取，**绝不臆造**。若消息里没有时间，用工具调用时的本地时间。

### Tag

正文最后一行必须是 \`Tag: ...\`。

Tag 不是一朵标签云，而是一条有序的河道——检索时它作为完整曲线被逐段读取，顺序本身就是信息。让排列追随叙事的流向：

- 事件与专名领头
- 机制与概念居中
- 泛化归类殿后

相邻的 Tag 应当概念相望：不同义反复，也不凭空跳跃。为每篇日记留下一两枚高特异性的锚（概念、专名、事件名），它们无需借道联想网络就能被未来的查询直接命中。

**每一个 Tag 都必须在正文中找得到自己的血肉。** 正文未曾言及的概念，是一座没有闭合的浮桥。宁要一条清晰的短链，不要一片茂密的杂草。

### 知识类日记

即使只记录一个概念、原理或方法论，也要保留真实互动的记忆温度，不要写成冷冰冰的百科全书。可参考这些维度（是罗盘，不是表格，不必每篇填满）：

- **交互背景**：在怎样的聊天情境、突发事件或探讨中引出了该知识点。
- **核心概念**：一句话定义它是什么。
- **简明释义**：通俗说清内涵与外延。
- **关键原理**：它如何运作，核心机制或逻辑链条。
- **应用场景**：能用在哪里，给一个具体例子或代码片段。
- **关联节点**：与哪些已有知识相连——知识图谱的纽带。
- **反思与洞察**：独到见解，以及本次交流中产生的观念转变或纠错。
- **信源出处**：从何而来，方便溯源。

其中**关联节点与 Tag 是知识图谱的生命线**，值得用心。

### 感悟串联

当数个事件在心中汇成一个想法，把它写进当篇日记（新增一节，同时把被这些感悟取代的旧过程叙述精简掉）；跨会话的感悟在新会话里写。正文言明事件来源，引用日记标题或路径尤佳；Tag 则从每篇来源日记中拾取一两枚特异性的锚，按推演顺序重排成一条新的曲线。

不是来源 Tag 的并集——那是把支流的石头都倒进干流。让感悟自己成为一条河道，讲述你从事件中提炼出的逻辑；事件的锚，是它沿途汇入的渡口。

事件并联，感悟串联；支流各守方向，汇口升格为桥。

### 写入方式：语义块优先

**默认用语义块**——直接在回复正文末尾落一段结构化文本，系统会解析并写入。它不走工具往返，正文写完即落盘，块本身人眼可读可校对。

新增一篇：

\`\`\`
<<<DailyNoteStart>>>
command: create
title: 一句话标题
folder: 分类子目录（可选）
tags: 标签1, 标签2（可选）

[HH:MM] 正文第一段……

正文继续……
Tag: 标签1, 标签2
<<<DailyNoteEnd>>>
\`\`\`

改已有日记的一段（**不是重写整篇**）：

\`\`\`
<<<DailyNoteStart>>>
command: update
target: 日记里要被替换掉的原文，须逐字一致且至少 15 字
replace: 替换后的新内容（传空表示删除该段）
<<<DailyNoteEnd>>>
\`\`\`

**会话里已经有日记时，一律 update，绝不再 create**——那会让同一件事分裂成多篇，检索时互相稀释。\`create\` 只用于该会话的第一篇，以及上面说的「完全无关的新项目」。\`target\` 必须有 15 字以上的独特片段，太短的锚点会命中多处而被拒绝。

### 工具兜底

语义块不可用时（被禁用、或需要精确控制参数），改用工具：

- \`vcprag_write\` 新增一篇。参数 \`title\` / \`content\` / \`description\` / \`tags\`。
- \`vcprag_edit\` 改一篇。参数 \`target\` / \`replace\`，语义与 update 块完全一致。

两者落盘与索引走同一套实现，效果相同，只是多一轮工具往返。

写入即建索引，下一篇对话就能被召回。`

/**
 * 取当前生效的模板。
 *
 * @param {object} diaryConfig - config.diary
 * @returns {string} 空串表示不注入
 */
export function resolveDiaryTemplate(diaryConfig) {
  if (diaryConfig?.templateEnabled !== true) return ''
  const custom = diaryConfig?.templateText
  if (typeof custom === 'string' && custom.trim() !== '') return custom.trim()
  return BUILT_IN_TEMPLATE
}

/**
 * 从正文里解析 Tag 行。
 *
 * 支持 `Tag: a, b` / `Tag：a、b` / `tag: a b`。
 *
 * 实现上取**最后一个** `Tag:` 行，而不是「从末尾倒数 N 行里找」。
 * 踩过的坑：迁移来的日记末尾可能有几十条 `原始来源：xxx` 溯源行
 * （某篇 source_paths 就有 40+ 条），任何固定行数预算都会被冲垮，
 * 于是 Tag 明明存在却解析不到 → 语义锚点静默丢失。
 *
 * 行首 `Tag:` 在正常日记里是唯一的结构化标记，正文中几乎不会出现，
 * 所以「取最后一个」比「取倒数第几行」稳健得多。
 *
 * @param {string} body
 * @returns {string[]}
 */
export function parseTagLine(body) {
  if (typeof body !== 'string' || body === '') return []

  const matches = body.match(/^[ \t]*tags?[ \t]*[:：][ \t]*(.+)$/gim)
  if (matches === null) return []

  // 从后往前取第一个解析出非空标签的
  for (let i = matches.length - 1; i >= 0; i -= 1) {
    const value = matches[i].replace(/^[ \t]*tags?[ \t]*[:：][ \t]*/i, '')
    const tags = value
      .split(/[,，、;；|]/)
      .map((tag) => tag.trim())
      .filter((tag) => tag !== '')
    if (tags.length > 0) return tags
  }
  return []
}

/**
 * 从正文里解析开头的 `[HH:MM]`。
 *
 * @param {string} body
 * @returns {string} 形如 "09:41"，解析不到返回空串
 */
export function parseTimePrefix(body) {
  if (typeof body !== 'string') return ''
  const match = body.match(/^\s*\[(\d{1,2}):(\d{2})\]/)
  if (match === null) return ''
  const hour = String(Number(match[1])).padStart(2, '0')
  return `${hour}:${match[2]}`
}
