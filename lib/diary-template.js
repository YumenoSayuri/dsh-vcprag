/**
 * 取当前生效的模板。
 *
 * @param {object} diaryConfig - config.diary
 * @returns {string} 空串表示不注入
 */
export function resolveDiaryTemplate(diaryConfig) {
  if (diaryConfig?.templateEnabled !== true) return ''
  const custom = diaryConfig?.templateText
  if (typeof custom === 'string' && custom.trim() !== '') return custom.trim()
  return BUILT_IN_TEMPLATE
}

/**
 * 从正文里解析 Tag 行。
 *
 * 支持 `Tag: a, b` / `Tag：a、b` / `tag: a b`。
 *
 * 实现上取**最后一个** `Tag:` 行，而不是「从末尾倒数 N 行里找」。
 * 踩过的坑：迁移来的日记末尾可能有几十条 `原始来源：xxx` 溯源行
 * （某篇 source_paths 就有 40+ 条），任何固定行数预算都会被冲垮，
 * 于是 Tag 明明存在却解析不到 → 语义锚点静默丢失。
 *
 * 行首 `Tag:` 在正常日记里是唯一的结构化标记，正文中几乎不会出现，
 * 所以「取最后一个」比「取倒数第几行」稳健得多。
 *
 * @param {string} body
 * @returns {string[]}
 */
export function parseTagLine(body) {
  if (typeof body !== 'string' || body === '') return []

  const matches = body.match(/^[ \t]*tags?[ \t]*[:：][ \t]*(.+)$/gim)
  if (matches === null) return []

  // 从后往前取第一个解析出非空标签的
  for (let i = matches.length - 1; i >= 0; i -= 1) {
    const value = matches[i].replace(/^[ \t]*tags?[ \t]*[:：][ \t]*/i, '')
    const tags = value
      .split(/[,，、;；|]/)
      .map((tag) => tag.trim())
      .filter((tag) => tag !== '')
    if (tags.length > 0) return tags
  }
  return []
}

/**
 * 从正文里解析开头的 `[HH:MM]`。
 *
 * @param {string} body
 * @returns {string} 形如 "09:41"，解析不到返回空串
 */
export function parseTimePrefix(body) {
  if (typeof body !== 'string') return ''
  const match = body.match(/^\s*\[(\d{1,2}):(\d{2})\]/)
  if (match === null) return ''
  const hour = String(Number(match[1])).padStart(2, '0')
  return `${hour}:${match[2]}`
}
